// Builds supabase/functions/transcribe/dashboard-single-file.ts: core.ts + index.ts in ONE file,
// for the Supabase dashboard editor (Edge Functions → Deploy a new function → Via Editor).
// Run from the repo root: npm run voice:bundle-function
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export function buildSingleFile(functionDir) {
  const core = readFileSync(join(functionDir, 'core.ts'), 'utf8');
  const index = readFileSync(join(functionDir, 'index.ts'), 'utf8');
  const wrapper = index
    .split('\n')
    .filter((line) => !/^import .* from '\.\/core\.ts';$/.test(line))
    .join('\n')
    .replace(/^\/\/.*\n(\/\/.*\n)*\n*/, '');
  return [
    '// GENERATED by `npm run voice:bundle-function` from core.ts + index.ts. Do not edit by hand.',
    '// Paste this WHOLE file into Supabase → Edge Functions → Deploy a new function → Via Editor,',
    '// name the function `transcribe`, keep "Verify JWT" on, then Deploy. See VOICE.md.',
    '',
    core.trimEnd(),
    '',
    '// ---------------------------------------------------------------------------',
    '// index.ts',
    '',
    wrapper.trimEnd(),
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const functionDir = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', 'supabase', 'functions', 'transcribe');
  const out = join(functionDir, 'dashboard-single-file.ts');
  writeFileSync(out, buildSingleFile(functionDir));
  console.log(`wrote ${out}`);
}
